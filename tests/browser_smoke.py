"""Browser smoke test using system Chromium. Run: PHP_BIN=... python3 tests/browser_smoke.py"""
from pathlib import Path
import sys
from playwright.sync_api import sync_playwright, expect
import test_instructions as workflow

server = workflow.InstructionWorkflow
server.setUpClass()
try:
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
        admin = browser.new_context(viewport={'width': 1440, 'height': 1000})
        page = admin.new_page()
        errors = []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.goto(server.base + '/admin/')
        page.get_by_label('Email address', exact=True).fill('owner@example.test')
        page.get_by_label('Password', exact=True).fill('Test owner password 123')
        page.get_by_role('button', name='Sign in', exact=True).click()
        expect(page.get_by_role('tab', name='Instruction videos')).to_be_visible()
        page.get_by_role('tab', name='Collection',exact=True).click()
        expect(page.locator('#product-name')).to_have_value('Invisible Deck')
        page.locator('#product-price').fill('11.50')
        photo = {'name': 'large-photo.png', 'mimeType': 'image/png', 'buffer': workflow.png_fixture(padding=6_000_000)}
        page.locator('[data-upload=product]').set_input_files(photo)
        expect(page.locator('#editor-status')).to_contain_text('Photo uploaded.', timeout=15000)
        product_photo = page.locator('[data-photo=product]').get_attribute('src')
        assert product_photo.startswith('/media.php?image=')
        page.get_by_role('button', name='Publish changes',exact=True).click()
        expect(page.locator('#editor-status')).to_contain_text('Your changes are published.')
        page.reload()
        page.get_by_role('tab', name='Collection',exact=True).click()
        expect(page.locator('[data-photo=product]')).to_have_attribute('src',product_photo)
        page.get_by_role('tab', name='Photos',exact=True).click()
        uploaded = {}
        for key in ['heroImage','bannerImage']:
            page.locator('[data-upload='+key+']').set_input_files(photo)
            expect(page.locator('#editor-status')).to_contain_text('Photo uploaded.',timeout=15000)
            uploaded[key] = page.locator('[data-photo='+key+']').get_attribute('src')
            assert uploaded[key].startswith('/media.php?image=')
        page.get_by_role('button', name='Publish changes',exact=True).click()
        expect(page.locator('#editor-status')).to_contain_text('Your changes are published.')
        public = admin.new_page()
        public.goto(server.base+'/')
        expect(public.locator('#collection-grid .product-image').first).to_have_attribute('src',product_photo)
        expect(public.locator('.hero-image img')).to_have_attribute('src',uploaded['heroImage'])
        expect(public.locator('.banner-frame img')).to_have_attribute('src',uploaded['bannerImage'])
        public.wait_for_function('() => document.querySelector(".hero-image img").naturalWidth > 0')
        public.close()
        page.get_by_role('tab', name='Instruction videos').click()
        page.get_by_role('button', name='+ Add instruction page').click()
        page.get_by_label('Trick / page title').fill('The Secret Deck')
        expect(page.get_by_label('Page address')).to_have_value('the-secret-deck')
        page.get_by_label('Public summary (optional)').fill('Learn to perform your new deck.')
        page.get_by_label('Private instructions / notes (optional)').fill('Keep the special deck secret.\nPractise before performing.')
        page.get_by_label('Shared trick password').fill('Deck-Secret')
        page.locator('#instruction-video-file').set_input_files(str(workflow.ROOT / 'tests/fixtures/sample.mp4'))
        expect(page.locator('#instruction-status')).to_contain_text('Video uploaded privately', timeout=15000)
        expect(page.get_by_label('Video link')).to_have_value('')
        expect(page.locator('#instruction-video-selected')).to_be_visible()
        page.get_by_role('switch', name='Publish this instruction page').check()
        page.get_by_role('button', name='Save instruction page', exact=True).click()
        expect(page.locator('#instruction-status')).to_contain_text('Instruction page saved.')
        page.reload()
        page.get_by_role('tab', name='Instruction videos').click()
        page.locator('#instruction-picker').get_by_role('button', name='The Secret Deck').click()
        expect(page.get_by_label('Replace shared password (optional)')).to_have_value('')
        expect(page.get_by_label('Video link')).to_have_value('')
        expect(page.locator('#instruction-video-selected')).to_be_visible()
        customer = browser.new_context(viewport={'width': 390, 'height': 844})
        view = customer.new_page()
        view.on('pageerror', lambda e: errors.append(str(e)))
        view.goto(server.base + '/')
        view.get_by_role('link', name='Watch your instructions').click()
        view.get_by_role('link', name='View instructions for The Secret Deck').click()
        expect(view.get_by_label('Trick password',exact=True)).to_be_visible()
        assert 'Keep the special deck secret' not in view.content()
        assert 'upload:' not in view.content()
        view.get_by_label('Trick password',exact=True).fill('wrong')
        view.get_by_role('button', name='Unlock instruction video').click()
        expect(view.get_by_role('alert')).to_contain_text('does not match')
        view.get_by_label('Trick password',exact=True).fill('Deck-Secret')
        view.get_by_role('button', name='Unlock instruction video').click()
        expect(view.get_by_role('heading', name='Before you perform')).to_be_visible()
        view.wait_for_function('() => document.querySelector("video").readyState >= 2')
        view.locator('video').evaluate('video => video.play()')
        view.wait_for_function('() => document.querySelector("video").ended')
        assert view.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile page overflows'
        Path('/workspace/artifacts').mkdir(exist_ok=True)
        view.screenshot(path='/workspace/artifacts/instructions-mobile.png', full_page=True)
        page.evaluate('scrollTo({top:0,behavior:"instant"})')
        page.screenshot(path='/workspace/artifacts/instructions-admin.png', full_page=True)
        page.get_by_label('Replace shared password (optional)').fill('New-Deck-Secret')
        page.get_by_role('button', name='Save instruction page', exact=True).click()
        expect(page.locator('#instruction-status')).to_contain_text('Instruction page saved.')
        view.reload()
        expect(view.get_by_label('Trick password',exact=True)).to_be_visible()
        assert not view.locator('video').count()
        view.screenshot(path='/workspace/artifacts/instructions-gate-mobile.png', full_page=True)
        page.get_by_role('switch', name='Publish this instruction page').uncheck()
        page.get_by_role('button', name='Save instruction page', exact=True).click()
        expect(page.locator('#instruction-status')).to_contain_text('The page is hidden')
        response = view.reload()
        assert response.status == 404
        page.on('dialog', lambda dialog: dialog.accept())
        page.get_by_role('button', name='Delete page', exact=True).click()
        expect(page.locator('#instruction-status')).to_contain_text('Instruction page deleted.')
        page.set_viewport_size({'width': 390, 'height': 844})
        page.get_by_role('button', name='+ Add instruction page').click()
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile admin overflows'
        assert not errors, errors
        browser.close()
        print('Browser smoke passed: product/opening/banner photos above 5 MB, publication/reload, instruction create/upload/save/reload, mobile unlock/playback, password revocation, hide/delete, responsive layout; no JavaScript errors.')
finally:
    server.tearDownClass()
